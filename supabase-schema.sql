-- SSF Morocco RP: starter schema for Supabase
-- Run this in Supabase SQL Editor.
-- Public visitors may INSERT applications. Only users with app_metadata.role = 'admin'
-- may SELECT/DELETE rows. Do not use a service_role key in browser code.

create table if not exists public.applications (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  full_name text not null check (char_length(full_name) between 2 and 60),
  discord_name text not null check (char_length(discord_name) between 2 and 60),
  age integer not null check (age between 13 and 99),
  availability text not null check (char_length(availability) between 1 and 100),
  experience text not null check (char_length(experience) between 10 and 1000),
  motivation text not null check (char_length(motivation) between 10 and 1000)
);

alter table public.applications enable row level security;

drop policy if exists "Anyone can submit an application" on public.applications;
create policy "Anyone can submit an application"
on public.applications for insert
to anon, authenticated
with check (
  char_length(full_name) between 2 and 60
  and char_length(discord_name) between 2 and 60
  and age between 13 and 99
  and char_length(availability) between 1 and 100
  and char_length(experience) between 10 and 1000
  and char_length(motivation) between 10 and 1000
);

drop policy if exists "Admins can read applications" on public.applications;
create policy "Admins can read applications"
on public.applications for select
to authenticated
using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "Admins can delete applications" on public.applications;
create policy "Admins can delete applications"
on public.applications for delete
to authenticated
using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

-- No UPDATE policy is created intentionally.
